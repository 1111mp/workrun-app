// Generate every packaged reference from the validation contract, preventing
// readable TypeScript and the runtime JSON Schema from drifting apart.
import { mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
const base = new URL(
  '../src-tauri/src/module/assistant/workflow_agent/reference/',
  import.meta.url,
);
const contracts = JSON.parse(
  readFileSync(new URL('../../../workflow/node-contracts.json', base), 'utf8'),
);
const resources = new URL('../src-tauri/resources/assistant/', import.meta.url);
const check = process.argv.includes('--check');
// This directory contains only generated assistant resources. Rebuild it so
// removed role documents cannot remain in a release bundle.
if (!check) rmSync(resources, { recursive: true, force: true });
function writeOutput(url, content) {
  if (check) {
    if (readFileSync(url, 'utf8') !== content)
      throw new Error(`Stale workflow reference: ${url.pathname}`);
  } else {
    mkdirSync(new URL('./', url), { recursive: true });
    writeFileSync(url, content);
  }
}
function output(path, content) {
  writeOutput(new URL(path, base), content);
  if (path !== 'node_references.rs')
    writeOutput(
      new URL(`workflow_agent/reference/${path}`, resources),
      content,
    );
}
// Built-in skills and shared references remain external files in every bundle.
for (const role of ['main_agent', 'workflow_agent']) {
  const source = new URL(
    `../src-tauri/src/module/assistant/${role}/`,
    import.meta.url,
  );
  for (const file of role === 'main_agent'
    ? [
        'AGENT.md',
        'INTENT.md',
        ...[
          'conversation',
          'task-planning',
          'capability-orchestration',
          'execution-collaboration',
          'result-delivery',
        ].map((name) => `skills/${name}.md`),
      ]
    : ['AGENT.md', 'skills/workflow-authoring.md']) {
    writeOutput(
      new URL(`${role}/${file}`, resources),
      readFileSync(new URL(file, source), 'utf8'),
    );
  }
}
for (const name of ['format', 'state', 'routing', 'recovery']) {
  writeOutput(
    new URL(`workflow_agent/reference/${name}.md`, resources),
    readFileSync(new URL(`${name}.md`, base), 'utf8'),
  );
}
for (const [topic, file] of [
  ['compensation', 'SAGA'],
  ['execution-recovery', 'RECOVERY'],
]) {
  writeOutput(
    new URL(`workflow_agent/reference/${topic}.md`, resources),
    readFileSync(new URL(`../../../workflow/${file}.md`, base), 'utf8'),
  );
}
function type(schema) {
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum)
    return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  if (schema.anyOf) return schema.anyOf.map(type).join(' | ');
  switch (schema.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'array':
      return `Array<${type(schema.items)}>`;
    case 'object': {
      const fields = Object.entries(schema.properties ?? {}).map(
        ([name, field]) => {
          const constraints = Object.fromEntries(
            Object.entries(field).filter(([key]) =>
              [
                'description',
                'minimum',
                'maximum',
                'minLength',
                'minItems',
                'uniqueItems',
                'default',
              ].includes(key),
            ),
          );
          const comment = Object.keys(constraints).length
            ? `/** ${JSON.stringify(constraints).replaceAll('*/', '* /')} */\n`
            : '';
          return `${comment}${JSON.stringify(name)}${schema.required?.includes(name) ? '' : '?'}: ${type(field)};`;
        },
      );
      if (schema.additionalProperties !== false)
        fields.push(
          `[key: string]: ${typeof schema.additionalProperties === 'object' ? type(schema.additionalProperties) : 'unknown'};`,
        );
      return `{\n${fields
        .map((field) =>
          field
            .split('\n')
            .map((line) => `  ${line}`)
            .join('\n'),
        )
        .join('\n')}\n}`;
    }
    default:
      throw new Error(`Unsupported schema type: ${JSON.stringify(schema)}`);
  }
}
if (!check) mkdirSync(new URL('nodes/', base), { recursive: true });
const index = [
  '# Workflow node index',
  '',
  'Read only the node skills needed for the current design. Details are packaged with the application; no source checkout is required.',
  '',
  '| Type | Purpose | Skill |',
  '| --- | --- | --- |',
];
const packaged = [
  '// Generated by scripts/generate-workflow-reference.mjs; do not edit.',
  '#[rustfmt::skip]',
  'pub const NODE_REFERENCES: &[(&str, &str, &str)] = &[',
];
for (const [kind, contract] of Object.entries(contracts)) {
  const name = kind
    .split('_')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
  const ts = `// Generated from JSON Schema. Runtime validation remains authoritative.\nexport interface ${name}NodeData ${type(contract.dataSchema)}\n`;
  const guide = `---\nname: workflow-node-${kind}\ndescription: ${contract.summary}\n---\n# ${contract.title} (${kind})\n\n${contract.guide}\n\n## Configuration\n\nTypeScript is a readable projection of the node data schema, not executable configuration. Numeric limits, uniqueness, additional-property rules and native semantics remain enforced by validate_workflow_draft. Request topic=node-schema with this node type only when the exact JSON Schema is needed.\n\n\`\`\`typescript\n${ts}\`\`\`\n\n## Connections\n\n${contract.sourceHandles.length ? `Allowed source handles: ${contract.sourceHandles.join(', ')}.` : 'No named source handles. Use an ordinary edge only if the node semantics above allow outgoing edges.'}\n\n## Example node\n\nReplace discovery placeholders with real resource IDs before validation.\n\n\`\`\`json\n${JSON.stringify(contract.example, null, 2)}\n\`\`\`\n`;
  output(`nodes/${kind}.d.ts`, ts);
  output(`nodes/${kind}.md`, guide);
  index.push(
    `| ${kind} | ${contract.summary} | [workflow-node-${kind}](nodes/${kind}.md) |`,
  );
  packaged.push(
    `    (${JSON.stringify(kind)}, ${JSON.stringify(contract.summary)}, "workflow_agent/reference/nodes/${kind}.md"),`,
  );
}
output('nodes.md', index.join('\n') + '\n');
output('node_references.rs', packaged.join('\n') + '\n];\n');
